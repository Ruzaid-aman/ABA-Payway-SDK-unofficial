#!/usr/bin/env node
/**
 * Regenerates the top-level guide stubs: for every `docs/guides/NN-<slug>.md`
 * that has a corresponding `docs/NN-<slug>.md` compatibility copy, rewrites the
 * copy as ONE honest mirror header followed by the guide body verbatim.
 *
 * The canonical guide is `docs/guides/NN-<slug>.md`; the root-level copy exists
 * so historical links to `docs/01-…`–`docs/22-…` keep resolving. Never edit a
 * stub by hand — edit the guide and re-run this script (`node
 * scripts/generate-guide-stubs.mjs`). `src/__tests__/guide-stubs.test.ts`
 * fails when a stub drifts from its guide or a source leaks a generated header.
 *
 * Not every numbered guide is mirrored on purpose: `docs/guides/23-close-transaction.md`
 * has no root stub (its root copy was removed when the public knowledge boundary
 * was tightened — release-gate commit `51d476b`). Unmirrored guides are listed,
 * not treated as an error. The reverse (a stub with no guide) IS an error: the
 * mirror source is gone and the stub can no longer be regenerated.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const guidesDir = path.join(repoRoot, 'docs', 'guides');
const docsDir = path.join(repoRoot, 'docs');
const NUMBERED_GUIDE = /^\d{2,}-.*\.md$/;

/** Exactly one header line, then a blank line, then the guide body verbatim. */
const headerFor = (name) =>
  `<!-- Mirrored from docs/guides/${name} — edits belong there; regenerated by scripts/generate-guide-stubs.mjs -->\n\n`;

function main() {
  const guides = readdirSync(guidesDir).filter((name) => NUMBERED_GUIDE.test(name)).sort();
  const stubs = existsSync(docsDir)
    ? readdirSync(docsDir).filter((name) => NUMBERED_GUIDE.test(name)).sort()
    : [];

  const guideSet = new Set(guides);
  const orphanStubs = stubs.filter((name) => !guideSet.has(name));
  if (orphanStubs.length) {
    console.error(
      `guide-stubs: FAIL — stub(s) under docs/ with no docs/guides/ source: ${orphanStubs.join(', ')}\n` +
        '  Restore the guide or delete the stub; the mirror cannot be regenerated.',
    );
    process.exit(1);
  }

  const stubSet = new Set(stubs);
  const pairs = guides.filter((name) => stubSet.has(name));
  const unmirrored = guides.filter((name) => !stubSet.has(name));

  let rewritten = 0;
  for (const name of pairs) {
    const body = readFileSync(path.join(guidesDir, name), 'utf8');
    const target = path.join(docsDir, name);
    const expected = headerFor(name) + body;
    if (readFileSync(target, 'utf8') !== expected) {
      writeFileSync(target, expected, 'utf8');
      rewritten += 1;
    }
  }

  console.log(
    `guide-stubs: checked ${pairs.length} stubs, rewrote ${rewritten} (docs/NN-*.md ← docs/guides/NN-*.md)` +
      (unmirrored.length ? `; unmirrored guides (no stub, by design): ${unmirrored.join(', ')}` : ''),
  );
}

main();
